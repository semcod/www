export function buildToonText(data, repoName) {
  return `# scan result | ${repoName} | ${new Date().toISOString().split("T")[0]}

HEALTH:
  score: ${data.health_score}
  grade: ${data.grade}

STATS:
  files: ${data.stats.total_files}
  lines: ${data.stats.total_lines}
  languages: ${JSON.stringify(data.stats.languages)}

COMPLEXITY:
  avg_cc: ${data.metrics.complexity.cc_avg.toFixed(2)}
  functions: ${data.metrics.complexity.functions}

DUPLICATION:
  groups: ${data.metrics.duplication.duplication_groups}
  recoverable_lines: ${data.metrics.duplication.recoverable_lines}

QUALITY:
  passed: ${data.metrics.quality.passed}
  warnings: ${data.metrics.quality.warnings}
  errors: ${data.metrics.quality.errors}

RECOMMENDATIONS[${data.recommendations.length}]:
${data.recommendations.map(toonRecommendationLine).join("\n")}`;
}

export function buildShareText(data, repoName) {
  return `🔍 Sprawdziłem jakość kodu repozytorium ${repoName}!

📊 Wynik: ${data.grade} (${data.health_score}%)
📁 ${data.stats.total_files} plików
📝 ${(data.stats.total_lines / 1000).toFixed(1)}k linii kodu

Analiza przez @semcod_dev`;
}

export function getResultTabContent(tab, data, repoName, isSandbox) {
  if (tab === "json") {
    return JSON.stringify(buildMetricsExportData(data, repoName, isSandbox), null, 2);
  }
  if (tab === "llm") {
    return buildPromptText(data, repoName);
  }
  if (tab === "markdown") {
    return buildMarkdownText(data, repoName);
  }
  if (tab === "toon") {
    return buildToonText(data, repoName);
  }
  if (tab === "share") {
    return buildShareText(data, repoName);
  }
  return "";
}

function downloadContent(content, filename, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function useDownloads(data, repoName, isSandbox) {
  const handleDownloadMetrics = useCallback(() => {
    downloadContent(
      JSON.stringify(buildMetricsExportData(data, repoName, isSandbox), null, 2),
      `${repoName.replace("/", "-")}-json.json`,
      "application/json"
    );
  }, [data, repoName, isSandbox]);

  const handleDownloadPrompt = useCallback(() => {
    downloadContent(
      buildPromptText(data, repoName),
      `${repoName.replace("/", "-")}-llm.txt`,
      "text/plain"
    );
  }, [data, repoName]);

  const handleDownloadMarkdown = useCallback(() => {
    downloadContent(
      buildMarkdownText(data, repoName),
      `${repoName.replace("/", "-")}-markdown.md`,
      "text/markdown"
    );
  }, [data, repoName]);

  const handleDownloadToon = useCallback(() => {
    downloadContent(
      buildToonText(data, repoName),
      `${repoName.replace("/", "-")}-toon.txt`,
      "text/plain"
    );
  }, [data, repoName]);

  const handleGenericDownload = useCallback((tab) => {
    if (tab === 'json') handleDownloadMetrics();
    else if (tab === 'llm') handleDownloadPrompt();
    else if (tab === 'markdown') handleDownloadMarkdown();
    else if (tab === 'toon') handleDownloadToon();
  }, [handleDownloadMetrics, handleDownloadPrompt, handleDownloadMarkdown, handleDownloadToon]);

  return {
    handleGenericDownload,
  };
}
