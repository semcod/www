import { useCallback } from "react";

export const TAB_TITLES = {
  share: "Share Content",
  json: "JSON Export",
  llm: "LLM Prompt",
  markdown: "Markdown Report",
  toon: "TOON Format",
};

function recommendationLabel(rec) {
  return rec?.title || rec?.message || rec?.description || "Recommendation";
}

function recommendationLine(rec, index) {
  return `${index + 1}. ${recommendationLabel(rec)} (Priority: ${rec.priority})`;
}

function markdownRecommendationLine(rec, index) {
  return `${index + 1}. **${recommendationLabel(rec)}** (Priority: ${rec.priority})`;
}

function toonRecommendationLine(rec, index) {
  return `  [${index + 1}] ${rec.priority.toUpperCase()}: ${recommendationLabel(rec)}`;
}

function filesContent(files) {
  if (!files || files.length === 0) {
    return "# No file contents available";
  }

  return files
    .map((file) => `### ${file.path}\n\`\`\`\n${file.content || ""}\n\`\`\``)
    .join("\n\n");
}

export function buildMetricsExportData(data, repoName, isSandbox) {
  return {
    repository: repoName,
    health_score: data.health_score,
    grade: data.grade,
    stats: data.stats,
    metrics: data.metrics,
    recommendations: data.recommendations,
    completed: data.completed,
    sandbox: isSandbox,
  };
}

export function buildPromptText(data, repoName) {
  return `# Code Analysis Report - ${repoName}
# Generated on: ${new Date().toISOString()}
# Health Score: ${data.health_score}% (${data.grade})

## Metrics
- Files: ${data.stats.total_files}
- Lines of Code: ${data.stats.total_lines}
- Languages: ${JSON.stringify(data.stats.languages, null, 2)}

## Complexity
- Average CC: ${data.metrics.complexity.cc_avg.toFixed(2)}
- Functions: ${data.metrics.complexity.functions}

## Duplication
- Groups: ${data.metrics.duplication.duplication_groups}
- Recoverable Lines: ${data.metrics.duplication.recoverable_lines}

## Quality
- Passed: ${data.metrics.quality.passed}
- Warnings: ${data.metrics.quality.warnings}
- Errors: ${data.metrics.quality.errors}

## Recommendations
${data.recommendations.map(recommendationLine).join("\n")}

## File Contents
${filesContent(data.files)}

---
Use this data to analyze code quality and suggest refactoring improvements via LLM.`;
}

