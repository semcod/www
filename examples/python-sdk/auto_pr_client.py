def main():
    print("=" * 50)
    print("Semcod Auto-PR SDK (gh + reDSL)")
    print("=" * 50)

    user = GhClient.get_user()
    if not user:
        print("ERROR: gh not authenticated. Run: gh auth login")
        sys.exit(1)

    print(f"GitHub user: {user}")

    examples = [
        ("1", "Quick Auto-PR (gh only)", example_1_gh_autopr),
        ("2", "ReDSL Health Check", example_2_redsl_health),
        ("3", "Ticket-driven Auto-PR", example_3_ticket_driven),
        ("4", "Batch Health Check", example_4_batch_health),
        ("5", "GitHub Issue + Ticket", example_5_issue_and_ticket),
        ("6", "ReDSL Preview (dry-run)", example_6_redsl_preview),
    ]

    for num, name, _ in examples:
        print(f"  {num}. {name}")
    print("  0. Run all")
    print("  q. Quit")

    choice = input("\nSelect: ").strip()
    if choice == "q":
        sys.exit(0)
    elif choice == "0":
        for _, _, func in examples:
            try:
                func()
            except Exception as e:
                print(f"Error: {e}")
    elif choice in [e[0] for e in examples]:
        examples[int(choice) - 1][2]()


if __name__ == "__main__":
    main()
