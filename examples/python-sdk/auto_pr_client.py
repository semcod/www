#!/usr/bin/env python3
"""
Semcod Auto-PR Python SDK — uses `gh` CLI for GitHub auth + Semcod API for reDSL.

Auth flow:
  1. Get GitHub token from `gh auth token`
  2. Exchange for Semcod session token via POST /auth/gh-token
  3. Use session token for all Semcod API calls
  4. Use `gh` CLI directly for GitHub operations (branch, commit, PR)
"""

import os
import sys
import json
import time
import base64
import subprocess
import requests
from typing import Dict, List, Optional
from dataclasses import dataclass
from enum import Enum


class TicketType(str, Enum):
    FEATURE = "feature"
    BUGFIX = "bugfix"


@dataclass
class SemcodConfig:
    base_url: str = "http://localhost:8003"
    timeout: int = 30


class GhClient:
    """GitHub CLI wrapper — uses `gh` which has valid token."""

    @staticmethod
    def get_token() -> str:
        result = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True)
        return result.stdout.strip()

    @staticmethod
    def get_user() -> str:
        result = subprocess.run(["gh", "api", "user", "--jq", ".login"], capture_output=True, text=True)
        return result.stdout.strip()

    @staticmethod
    def api(endpoint: str, repo: str = "", method: str = "GET", fields: dict = None) -> dict:
        cmd = ["gh", "api", endpoint]
        if repo:
            cmd += ["--repo", repo]
        if fields and method != "GET":
            for k, v in fields.items():
                cmd += ["-f", f"{k}={v}"]
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
        if result.returncode != 0:
            return {"error": result.stderr.strip()}
        try:
            return json.loads(result.stdout)
        except json.JSONDecodeError:
            return {"raw": result.stdout.strip()}

    @staticmethod
    def list_repos(limit: int = 10) -> List[dict]:
        result = subprocess.run(
            ["gh", "repo", "list", "--limit", str(limit),
             "--json", "nameWithOwner,isPrivate,defaultBranch"],
            capture_output=True, text=True
        )
        try:
            return json.loads(result.stdout)
        except:
            return []

    @staticmethod
    def create_pr(repo: str, branch: str, title: str, body: str = "", base: str = "main") -> dict:
        result = subprocess.run(
            ["gh", "pr", "create", "--repo", repo,
             "--head", branch, "--base", base,
             "--title", title, "--body", body or "Auto-generated by Semcod",
             "--json", "url,number"],
            capture_output=True, text=True
        )
        try:
            return json.loads(result.stdout)
        except:
            return {"error": result.stderr.strip()}

    @staticmethod
    def create_branch(repo: str, branch: str, sha: str) -> bool:
        result = subprocess.run(
            ["gh", "api", f"repos/{repo}/git/refs",
             "-f", f"ref=refs/heads/{branch}", "-f", f"sha={sha}"],
            capture_output=True, text=True
        )
        return result.returncode == 0

    @staticmethod
    def commit_file(repo: str, path: str, content: str, branch: str,
                    message: str = "semcod: auto-commit") -> dict:
        encoded = base64.b64encode(content.encode()).decode()
        result = subprocess.run(
            ["gh", "api", f"repos/{repo}/contents/{path}",
             "-X", "PUT",
             "-f", f"message={message}",
             "-f", f"content={encoded}",
             "-f", f"branch={branch}"],
            capture_output=True, text=True
        )
        try:
            return json.loads(result.stdout)
        except:
            return {"error": result.stderr.strip()}

    @staticmethod
    def create_issue(repo: str, title: str, body: str = "", labels: List[str] = None) -> dict:
        cmd = ["gh", "issue", "create", "--repo", repo,
               "--title", title, "--body", body or "Auto-created by Semcod",
               "--json", "url,number"]
        if labels:
            cmd += ["--label", ",".join(labels)]
        result = subprocess.run(cmd, capture_output=True, text=True)
        try:
            return json.loads(result.stdout)
        except:
            return {"error": result.stderr.strip()}


class SemcodClient:
    """Semcod API client — authenticates via gh token exchange."""

    def __init__(self, config: SemcodConfig):
        self.config = config
        self.session = requests.Session()
        self.session_token = self._authenticate()

    def _authenticate(self) -> str:
        """Exchange gh token for Semcod session token."""
        gh_token = GhClient.get_token()
        if not gh_token:
            return ""
        try:
            resp = requests.post(
                f"{self.config.base_url}/auth/gh-token",
                params={"token": gh_token},
                timeout=self.config.timeout
            )
            if resp.status_code == 200:
                token = resp.json().get("session_token", "")
                self.session.headers.update({
                    "Authorization": f"Bearer {token}",
                    "Content-Type": "application/json"
                })
                return token
        except Exception:
            pass
        return ""

    def _request(self, method: str, endpoint: str, data: dict = None) -> dict:
        if not self.session_token:
            return {"error": "Not authenticated (no Semcod session)"}
        url = f"{self.config.base_url}{endpoint}"
        try:
            response = self.session.request(method=method, url=url, json=data, timeout=self.config.timeout)
            response.raise_for_status()
            return response.json()
        except requests.exceptions.RequestException as e:
            return {"error": str(e)}

    # Tickets
    def create_ticket(self, title: str, repo: str, ticket_type: TicketType,
                      description: str = "", priority: str = "medium") -> dict:
        return self._request("POST", "/api/tickets", {
            "title": title, "repo": repo,
            "ticket_type": ticket_type.value,
            "description": description, "priority": priority
        })

    def get_tickets(self, status: str = None) -> dict:
        endpoint = "/api/tickets" + (f"?status={status}" if status else "")
        return self._request("GET", endpoint)

    def process_ticket(self, ticket_id: str, project_path: str,
                       max_actions: int = 10, dry_run: bool = False) -> dict:
        return self._request("POST", f"/api/tickets/{ticket_id}/process", {
            "project_path": project_path,
            "max_actions": max_actions, "dry_run": dry_run
        })

    def get_ticket_status(self, ticket_id: str) -> dict:
        return self._request("GET", f"/api/tickets/{ticket_id}/status")

    def get_ticket_stats(self) -> dict:
        return self._request("GET", "/api/tickets/stats")

    # ReDSL
    def get_redsl_status(self) -> dict:
        return self._request("GET", "/api/redsl/status")

    def redsl_health(self, project_path: str) -> dict:
        return self._request("POST", "/api/redsl/health", {"project_path": project_path})

    def redsl_refactor(self, project_path: str, max_actions: int = 10, dry_run: bool = True) -> dict:
        return self._request("POST", "/api/redsl/refactor", {
            "project_path": project_path,
            "max_actions": max_actions, "dry_run": dry_run
        })


