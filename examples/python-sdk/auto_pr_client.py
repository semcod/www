def example_1_gh_autopr():
    """Create PR using gh CLI directly (no Semcod needed)."""
    print("=== Example 1: gh CLI Auto-PR ===")
    user = GhClient.get_user()
    print(f"GitHub user: {user}")

    repos = GhClient.list_repos(limit=3)
    if not repos:
        print("No repos found")
        return

    repo = repos[0]["nameWithOwner"]
    print(f"Using repo: {repo}")

    repo_info = GhClient.api(f"repos/{repo}")
    default_branch = repo_info.get("default_branch", "main")
    ref = GhClient.api(f"repos/{repo}/git/refs/heads/{default_branch}")
    sha = ref.get("object", {}).get("sha", "")

    if not sha:
        print(f"ERROR: Cannot get SHA for {repo}")
        return

    branch = f"semcod-fix-{int(time.time())}"
    print(f"Creating branch: {branch}")

    if GhClient.create_branch(repo, branch, sha):
        GhClient.commit_file(repo, "semcod_test.txt", "# Semcod Auto-PR test\n", branch)
        pr = GhClient.create_pr(repo, branch, "semcod: auto-fix test")
        print(f"✅ PR created: {pr.get('url', 'ERROR')}")
    else:
        print("ERROR: Failed to create branch")


def example_2_redsl_health():
    """Check health score via Semcod reDSL."""
    print("\n=== Example 2: ReDSL Health Check ===")
    client = SemcodClient(SemcodConfig())

    if not client.session_token:
        print("Semcod not available — showing gh repo info instead")
        repos = GhClient.list_repos(limit=3)
        for r in repos:
            print(f"  {r['nameWithOwner']}")
        return

    status = client.get_redsl_status()
    print(f"ReDSL status: {status}")

    repos = GhClient.list_repos(limit=3)
    for r in repos:
        repo = r["nameWithOwner"]
        project = f"/mnt/project/{repo.replace('/', '-')}"
        health = client.redsl_health(project)
        score = health.get("score", "?")
        print(f"  {repo}: health={score}")


def example_3_ticket_driven():
    """Ticket-driven Auto-PR."""
    print("\n=== Example 3: Ticket-driven Auto-PR ===")
    client = SemcodClient(SemcodConfig())

    if not client.session_token:
        print("Semcod not available — falling back to gh CLI")
        example_1_gh_autopr()
        return

    repos = GhClient.list_repos(limit=1)
    if not repos:
        print("No repos")
        return

    repo = repos[0]["nameWithOwner"]
    ticket = client.create_ticket(
        title="Add pagination to users endpoint",
        repo=repo, ticket_type=TicketType.FEATURE,
        description="Add limit/offset pagination", priority="high"
    )

    if "error" in ticket:
        print(f"Ticket failed: {ticket['error']}")
        example_1_gh_autopr()
        return

    ticket_id = ticket.get("ticket_id", "")
    print(f"Ticket: {ticket_id}")

    project = f"/mnt/project/{repo.replace('/', '-')}"
    result = client.process_ticket(ticket_id, project, max_actions=10)
    print(f"Process result: {json.dumps(result, indent=2)[:300]}")


def example_4_batch_health():
    """Batch health check all repos."""
    print("\n=== Example 4: Batch Health Check ===")
    client = SemcodClient(SemcodConfig())
    repos = GhClient.list_repos(limit=10)

    for r in repos:
        repo = r["nameWithOwner"]
        if client.session_token:
            project = f"/mnt/project/{repo.replace('/', '-')}"
            health = client.redsl_health(project)
            score = health.get("score", "?")
            print(f"  {repo}: health={score}")
        else:
            print(f"  {repo}: (Semcod unavailable)")


def example_5_issue_and_ticket():
    """Create GitHub Issue + Semcod ticket."""
    print("\n=== Example 5: GitHub Issue + Semcod Ticket ===")
    repos = GhClient.list_repos(limit=1)
    if not repos:
        print("No repos")
        return

    repo = repos[0]["nameWithOwner"]
    issue = GhClient.create_issue(repo, "Bug: Auth fails on token expiry",
                                  "Auth fails when JWT expires", ["bug"])
    print(f"GitHub issue: {issue.get('url', 'ERROR')}")

    client = SemcodClient(SemcodConfig())
    if client.session_token:
        ticket = client.create_ticket(
            title="Fix auth token expiry", repo=repo,
            ticket_type=TicketType.BUGFIX,
            description=f"GitHub issue: {issue.get('url', '')}",
            priority="high"
        )
        print(f"Semcod ticket: {ticket}")
    else:
        print("Semcod unavailable — issue created on GitHub only")


def example_6_redsl_preview():
    """ReDSL dry-run preview."""
    print("\n=== Example 6: ReDSL Preview (dry-run) ===")
    client = SemcodClient(SemcodConfig())

    if not client.session_token:
        print("Semcod not available")
        return

    repos = GhClient.list_repos(limit=1)
    if not repos:
        print("No repos")
        return

    repo = repos[0]["nameWithOwner"]
